/// The eye shapes a ghost face can draw.
enum EyeStyle {
  /// Plain round eyes.
  round,

  /// Wide open, alert eyes.
  wide,

  /// Eyes that sag towards the outer corners.
  droopy,

  /// Eyes closed halfway by a lid.
  halfClosed,

  /// Crossed-out eyes.
  cross,

  /// Upturned arcs, closed in delight.
  happyArc,
}
